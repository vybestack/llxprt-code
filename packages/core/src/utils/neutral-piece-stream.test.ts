import { describe, expect, it } from 'bun:test';
import { NeutralPieceStream } from './neutral-piece-stream.js';
import { estimateTokens } from './toolOutputLimiter.js';
import { countBpePiece, encodingBpeRanks } from './neutral-long-piece.js';

function count(text: string, chunkBytes: number): number {
  const counter = new NeutralPieceStream();
  const bytes = Buffer.from(text);
  for (let start = 0; start < bytes.length; start += chunkBytes)
    counter.append(bytes.subarray(start, start + chunkBytes));
  return counter.finish();
}

describe('incremental neutral BPE piece counts', () => {
  it('matches the whole-text oracle across byte and Unicode boundaries', () => {
    const pieces = [
      '',
      'hello',
      'HELLO',
      'abcdefghijk',
      '汉字汉字',
      '🙂🙂🙂',
      '123',
      "can't",
    ];
    for (const text of pieces) {
      const expected = estimateTokens(text);
      for (let size = 1; size <= Buffer.byteLength(text) + 1; size++)
        expect(count(text, size)).toBe(expected);
    }
  });

  it('matches whole-text counts for long unsplittable pieces', () => {
    for (const text of [
      'a'.repeat(131072),
      'abcde'.repeat(30000),
      '!'.repeat(131072),
      ' '.repeat(131072),
      '汉'.repeat(40000),
    ]) {
      const expected = estimateTokens(text);
      for (const size of [7, 65536]) expect(count(text, size)).toBe(expected);
    }
  });

  it('matches independently counted generated word pieces', () => {
    let seed = 854;
    for (let trial = 0; trial < 512; trial++) {
      let text = '';
      for (let at = 0; at < 5 + (trial % 75); at++) {
        seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
        text += String.fromCharCode(97 + (seed % 26));
      }
      expect(count(text, 3)).toBe(estimateTokens(text));
    }
  });

  it('matches the ranked-merge oracle at every generated byte prefix', () => {
    const ranks = encodingBpeRanks('o200k_base');
    const fragments = [
      'arrival',
      '汉字',
      String.fromCodePoint(0x1f642),
      'ABCdef',
      "'re",
      '12345',
      '!/',
      String.fromCharCode(32, 13, 10),
      'é',
    ];
    let seed = 854;
    for (let trial = 0; trial < 128; trial++) {
      let text = '';
      for (let at = 0; at < 12; at++) {
        seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
        text += fragments[seed % fragments.length];
      }
      const bytes = Buffer.from(text);
      const counter = new NeutralPieceStream();
      for (let at = 0; at < bytes.length; at++) {
        counter.append(bytes.subarray(at, at + 1));
        expect(counter.count).toBe(
          countBpePiece(bytes.subarray(0, at + 1), ranks),
        );
      }
    }
  });

  it('rejects writes after the piece has finished', () => {
    const counter = new NeutralPieceStream();
    counter.append(Buffer.from('hello'));
    expect(counter.finish()).toBe(estimateTokens('hello'));
    expect(() => counter.append(Buffer.from('x'))).toThrow('piece is finished');
  });
});
