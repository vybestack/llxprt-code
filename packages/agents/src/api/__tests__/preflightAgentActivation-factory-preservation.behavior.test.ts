async function settleEngineRelease(
  steps: ReadonlyArray<() => void | Promise<void>>,
  previousReplay: string | undefined,
): Promise<void> {
  try {
    await runCleanupSteps(steps);
  } finally {
    if (previousReplay === undefined) delete process.env.LLXPRT_FAKE_RESPONSES;
    else process.env.LLXPRT_FAKE_RESPONSES = previousReplay;
  }
}

describe('preflight agent-owned runtime factory assembly @plan:ISSUE-3222 @requirement:REQ-3222-AC2', () => {
  let promptDirectory: string;
  const previousPrompts = process.env.LLXPRT_PROMPTS_DIR;
  beforeAll(async () => {
    promptDirectory = await mkdtemp(join(tmpdir(), 'engine-prompts-'));
    process.env.LLXPRT_PROMPTS_DIR = promptDirectory;
    await initializePromptSystem();
  });
  afterAll(async () => {
    if (previousPrompts === undefined) delete process.env.LLXPRT_PROMPTS_DIR;
    else process.env.LLXPRT_PROMPTS_DIR = previousPrompts;
    await rm(promptDirectory, { recursive: true, force: true });
  });

  const builtCredentials = useOwnedCredentials();
  let builtCallerConfig: Config;
  let builtCallerSettings: SettingsService;
  let builtCallerSettingsOwner: SessionSettingsOwner;
  let builtCallerPolicy: RuntimePolicyOwner;
  let builtCallerMcp: McpRuntimeOwner;
  let builtCallerManager: ReturnType<typeof acquirePreferredProviderManager>;
  let builtCallerOwner: SessionClientOwner;
  let builtCallerClose: () => Promise<void>;
  let builtCallerFactories: AgentRuntimeFactoryBindings;
  let builtCallerRelease: AcquisitionRelease;
  let builtCallerFiles: ProviderFileLifecycle;
  let builtCallerRuntimeId: string;
  let builtCallerOAuth: ReturnType<typeof acquirePreferredOAuth>;
  let builtCallerTokenizer: ReturnType<typeof configureProviderTokenizer>;
  let builtCallerContent: ReturnType<
    typeof createRuntimeContentGeneratorFactory
  >;

  async function openbuiltCaller(
    fixture: string,
    overrides: Readonly<Partial<AgentConfig>> = {},
    suppliedFactories: Readonly<Partial<AgentRuntimeFactoryBindings>> = {},
    skillSettings: Pick<
      ConfigParameters,
      'enableExtensionReloading' | 'storageRoot'
    > = {},
    extensionLoader?: ExtensionLoader,
    skillOperations?: WorkspaceSkillAssemblyOperations,
  ): Promise<void> {
    const previousReplay = process.env.LLXPRT_FAKE_RESPONSES;
    process.env.LLXPRT_FAKE_RESPONSES = fileURLToPath(
      new URL('./fixtures/' + fixture, import.meta.url),
    );
    const directory = await realpath(
      await mkdtemp(join(tmpdir(), 'builtCaller-adoption-')),
    );
    const selection: AgentConfig = {
      provider: 'fake',
      model: 'fake-model',
      sessionId: randomUUID(),
      ...overrides,
      workingDir:
        overrides.workingDir === undefined
          ? directory
          : await realpath(overrides.workingDir),
    };
    const parameters = { ...toConfigParameters(selection), ...skillSettings };
    parameters.interactive = true;
    if (overrides.hooks !== undefined) parameters.enableHooks = true;
    if (
      overrides.filesystemOwner === undefined &&
      (overrides.harness?.includeProcessCwd ?? true)
    )
      parameters.includeDirectories = [
        ...(parameters.includeDirectories ?? []),
        process.cwd(),
      ];
    builtCallerConfig = new Config(parameters);
    builtCallerFactories = {
      ...createAgentRuntimeFactoryBindings(),
      ...suppliedFactories,
    };
    builtCallerSettings = new SettingsService();
    for (const [key, value] of Object.entries(
      builtCallerConfig.getInitialSettings(),
    ))
      builtCallerSettings.set(key, value);
    builtCallerPolicy = new RuntimePolicyOwner(builtCallerConfig);
    injectConfirmationForcingPolicy(builtCallerPolicy.session.confirmation);
    builtCallerMcp = await buildTestMcpRuntime(
      builtCallerConfig,
      builtCallerPolicy.session.messageBus,
      overrides,
      extensionLoader,
      builtCallerPolicy,
      skillOperations,
    );
    acquirebuiltCallerProviders();
    const media = new SessionMediaOwner(
      builtCallerConfig.projectTempDir,
      1024 * 1024 * 1024,
    );
    builtCallerOwner = await createCapturedSessionOwner(
      builtCallerConfig,
      assembleTaskSchemaPolicy(builtCallerSettings),
      builtCallerManager,
      builtCallerFactories.agentClientFactory,
      media.store,
      builtCallerMcp.readInstructions,
      builtCallerMcp.workspacePaths,
      builtCallerSettingsOwner,
      builtCallerContent,
      builtCallerTokenizer,
    );
    builtCallerOwner.bindMcpRuntime(builtCallerMcp);
    builtCallerOwner.bindProviderFiles(builtCallerFiles, (provider) =>
      builtCallerOAuth.composeRetryOperations(provider),
    );
    builtCallerOwner.bindHooks();
    builtCallerClose = settleEngineRelease.bind(
      undefined,
      [
        () => builtCallerOwner.dispose(),
        () => builtCallerRelease.close(),
        () => media.dispose(),
        () => builtCallerMcp.dispose(),
        () => builtCallerConfig.dispose(),
        () => rm(directory, { recursive: true, force: true }),
      ],
      previousReplay,
    );
    try {
      await preparePreferredProviderCompletion(
        builtCallerConfig,
        builtCallerSettings,
        builtCallerSettingsOwner,
        builtCallerManager,
        builtCallerOAuth,
        builtCallerRuntimeId,
        builtCallerTokenizer,
        undefined,
      );
      await builtCallerMcp.initialize();
      await activatebuiltCallerClient(selection.activation);
    } catch (primary) {
      await cleanupAfterFailure(primary, builtCallerClose);
    }
  }
  function acquirebuiltCallerProviders(): void {
    builtCallerRuntimeId = 'builtCaller-' + randomUUID();
    builtCallerRelease = new AcquisitionRelease();
    builtCallerSettingsOwner = new SessionSettingsOwner(builtCallerSettings);
    builtCallerRelease.acquire('settings', () =>
      builtCallerSettingsOwner.dispose(),
    );
    builtCallerSettingsOwner.initializeProviderSelection(
      builtCallerConfig.getProvider(),
      builtCallerConfig.getModel(),
    );
    builtCallerSettingsOwner.bindTelemetry(builtCallerConfig);
    builtCallerFiles = new ProviderFileLifecycle({
      maxFiles: 100,
      maxBytes: 512 * 1024 * 1024,
    });
    for (const scope of [
      builtCallerRuntimeId,
      builtCallerConfig.getSessionId(),
    ])
      builtCallerRelease.acquire('files', () =>
        releaseAdoptedFileScope(builtCallerFiles, scope),
      );
    builtCallerManager = acquirePreferredProviderManager(
      builtCallerConfig,
      builtCallerSettings,
      builtCallerSettingsOwner,
      builtCallerFiles,
      builtCallerRuntimeId,
      builtCredentials().authority,
      builtCallerRelease,
    );
    const factoriesTokenizer = configureProviderTokenizer(builtCallerManager);
    const factoriesContent = createRuntimeContentGeneratorFactory();
    builtCallerTokenizer = factoriesTokenizer;
    builtCallerContent = factoriesContent;
    builtCallerOAuth = acquirePreferredOAuth(
      undefined,
      builtCallerPolicy.session.messageBus,
      builtCallerConfig,
      builtCallerSettings,
      builtCallerManager,
      builtCallerRuntimeId,
      builtCallerMcp.profileDefinitions,
      builtCredentials().authority,
      builtCallerRelease,
      undefined,
    );
  }
  async function activatebuiltCallerClient(
    intent: ProviderActivationIntent = {
      provider: builtCallerConfig.getProvider(),
      model: builtCallerConfig.getModel(),
    },
  ): Promise<void> {
    const activation = await executeProviderActivation(
      builtCallerConfig,
      intent,
      assembleProviderSwitch(
        builtCallerConfig,
        builtCallerSettings,
        builtCallerManager,
        builtCallerOAuth,
        () => 'agent',
        () => builtCallerOwner.refreshAuth(),
        builtCallerSettingsOwner,
      ),
      builtCallerSettings,
      builtCallerManager,
      (method) => builtCallerOwner.refreshAuth(method),
      assembleModelSelection(builtCallerSettingsOwner),
    );
    requireCallerActivation(activation);
    await builtCallerOwner.initializeTools();
    await capturedSessionClient(builtCallerOwner).startChat();
  }

  it('installs absent client and task defaults before activation and executes an adopted tool turn', async () => {
    await openbuiltCaller('tool-call-then-answer.jsonl');
    expect(builtCallerMcp.toolSelection.getTool('task')).toBeUndefined();
    const manager = builtCallerManager;

    const operation = await assembleAgentActivationBootstrap(
      builtCallerConfig,
      builtCallerSettings,
      manager,
      null,
      () => undefined,
      'borrowed',
      capturedSessionClient(builtCallerOwner),
      builtCallerMcp,
    );
    const intent: ProviderActivationIntent = {
      provider: 'fake',
      authMode: 'auto',
    };
    let agent: Awaited<ReturnType<typeof fromConfig>> | undefined;
    try {
      const result = await operation.preflight(intent);
      expect(result.authFailed).toBe(false);
      expect(result.activeProvider).toBe('fake');
      if (!result.token) throw new Error('Missing preflight token');
      agent = await fromConfig(
        builtCallerConfig,
        builtCallerSettings,
        { activation: intent },
        builtCallerSettingsOwner,
        builtCallerManager,
        undefined,
        builtCallerPolicy.session.messageBus,
        builtCallerMcp,
        { operation, token: result.token },
        capturedSessionClient(builtCallerOwner),
      );
      const events = await drain(agent.stream('read package metadata'));
      expect(countType(events, 'tool-result')).toBeGreaterThan(0);
      expect(countType(events, 'done')).toBe(1);
      expect(agent.tools.get('task')?.name).toBe('task');
    } finally {
      await agent?.dispose();
      await builtCallerClose();
    }
  });

  it('preserves caller client factory and adopted scheduler handle lifetime after preflight', async () => {
    const clientFactory =
      createAgentRuntimeFactoryBindings().agentClientFactory;
    const callerClients = new Set<ReturnType<typeof clientFactory>>();
    const runtimeFactoryBindings = {
      ...createAgentRuntimeFactoryBindings(),
      agentClientFactory: (...args: Parameters<typeof clientFactory>) => {
        const client = clientFactory(...args);
        callerClients.add(client);
        return client;
      },
    };
    await openbuiltCaller(
      'tool-call-then-answer.jsonl',
      {},
      runtimeFactoryBindings,
    );
    const manager = builtCallerManager;

    const operation = await assembleAgentActivationBootstrap(
      builtCallerConfig,
      builtCallerSettings,
      manager,
      null,
      () => undefined,
      'borrowed',
      capturedSessionClient(builtCallerOwner),
      builtCallerMcp,
    );
    const intent: ProviderActivationIntent = {
      provider: 'fake',
      cliOverrides: { key: 'caller-preflight-key' },
      authMode: 'auto',
    };
    let created = 0;
    let active = 0;
    let agent: Awaited<ReturnType<typeof fromConfig>> | undefined;
    try {
      const result = await operation.preflight(intent);
      expect(result.authFailed).toBe(false);
      if (!result.token) throw new Error('Missing preflight token');
      agent = await fromConfig(
        builtCallerConfig,
        builtCallerSettings,
        { activation: intent },
        builtCallerSettingsOwner,
        builtCallerManager,
        undefined,
        builtCallerPolicy.session.messageBus,
        builtCallerMcp,
        { operation, token: result.token },
        capturedSessionClient(builtCallerOwner),
        undefined,
        undefined,
        undefined,
        undefined,
        undefined,
        undefined,
        undefined,
        undefined,
        undefined,
        undefined,
        undefined,
        undefined,
        undefined,
        undefined,
        undefined,
        undefined,
        undefined,
        undefined,
        undefined,
        undefined,
        undefined,
        undefined,
        undefined,
        undefined,
        () => {
          created += 1;
          active += 1;
          return {
            dispose: () => {
              active -= 1;
            },
          };
        },
      );
      const events = await drain(agent.stream('read package metadata'));
      expect(countType(events, 'tool-result')).toBeGreaterThan(0);
      expect(created).toBeGreaterThan(0);
      expect(active).toBe(created);
      expect(callerClients.has(capturedSessionClient(builtCallerOwner))).toBe(
        true,
      );
      await agent.dispose();
      expect(active).toBe(0);
    } finally {
      await agent?.dispose();
      await builtCallerClose();
    }
  });
});

function requireCallerActivation(
  result: Awaited<ReturnType<typeof executeProviderActivation>>,
): void {
  if (result.authFailed) throw result.authError;
}
